import './scripts/local-env.mjs';
import swc from 'unplugin-swc';
import { defineConfig } from 'vitest/config';
import { workspaceAliases } from './vitest.shared.config.js';

/**
 * Интеграционные проверки (ADR-0006): модуль целиком поверх реальной PostgreSQL.
 *
 * Адрес базы — `TEST_DATABASE_URL`, по умолчанию локальная `zvonix_test`.
 * Тесты очищают схему, поэтому имя базы обязано оканчиваться на `_test` —
 * это проверяется до первого запроса.
 *
 * Транспиляция здесь идёт через SWC, а не через штатный esbuild: esbuild не генерирует
 * метаданные декораторов, а контейнер NestJS по ним определяет, что подставить
 * в конструктор. Без них приложение не поднимается вовсе — и проверялось бы
 * не приложение, а способность теста обойти его сборку.
 */
export default defineConfig({
  plugins: [swc.vite({ module: { type: 'es6' } })],
  resolve: { alias: workspaceAliases },
  test: {
    include: ['{apps,packages}/*/src/**/*.integration.test.ts'],
    exclude: ['**/node_modules/**', '**/dist/**'],
    // Общая база на все файлы: параллельные наборы, роняющие и создающие схему,
    // мешали бы друг другу. Внутри файла тесты независимы и создают свои данные сами.
    fileParallelism: false,
    /**
     * Пул оставлен штатным — процесс на файл.
     *
     * Набор примерно в половине прогонов теряет один файл целиком: `Worker exited
     * unexpectedly`, ни одного упавшего утверждения. Измерениями исключены соединения
     * с базой (пик 4 из 100), нативный модуль хеширования (60 запусков подряд чисто),
     * эфемерные порты Windows (пик 227 из 16 384) и подъём приложения (30 запусков
     * подряд чисто). Остаётся рабочий процесс пула vitest.
     *
     * Исключено 2026-09-09, каждое отдельным прогоном:
     * **нехватка памяти** — файл потерян при 7,6 ГБ свободных (гейт печатает замер
     * перед шагом), а прежний вывод «дело в памяти» был совпадением;
     * **`process.exit()`** — под `--trace-exit` потеря воспроизвелась без единой
     * трассировки, значит его не звал и никто из зависимостей;
     * **фатальная ошибка Node и необработанное исключение** — под
     * `--report-on-fatalerror --report-uncaught-exception` потеря воспроизвелась,
     * а отчёт не появился (сам механизм отчётов проверен отдельно, он работает);
     * **нативное падение** — в журнале приложений Windows записи нет, хотя падения
     * chrome.exe там есть;
     * **снятие антивирусом** — `Get-MpThreatDetection` пуст.
     * Остаётся снятие процесса снаружи. Файл при этом каждый раз другой: опознаётся
     * по разнице «ожидалось / прошло тестов» — 6 это `partner-report`, 8 — один
     * из трёх файлов `routing`.
     *
     * Один процесс на весь набор (`maxWorkers: 1, isolate: false`) **проверен и отвергнут**
     * 2026-09-05: процесс умирает так же, но уносит с собой все оставшиеся файлы —
     * девять пройденных из двадцати восьми вместо двадцати семи. Вдвое быстрее, но гейт,
     * теряющий восемнадцать файлов на одной осечке, хуже медленного.
     *
     * Виновника из штатного отчёта не видно — он называет только упавшее. Ловится
     * запуском с `--reporter=verbose`: у погибшего файла тесты в выводе есть,
     * а итоговой строки нет, и он оказывается последним.
     *
     * Следующий шаг — прогон на Ubuntu: все наблюдения сделаны в Windows вопреки
     * ADR-0007, и ответ бесплатен при первом же прогоне CI. Подробности и пойманные
     * случаи — в TASKS.md.
     */
    testTimeout: 30_000,
    hookTimeout: 90_000,
  },
});
