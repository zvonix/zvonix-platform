/**
 * Схемы входных данных записей разговоров.
 */

import { z } from 'zod';

export const prepareUploadSchema = z.object({
  /** Вызов, запись которого выгружается. */
  callId: z.uuid('должен быть идентификатором'),
});

export const confirmUploadSchema = z.object({
  callId: z.uuid('должен быть идентификатором'),

  durationSeconds: z.coerce
    .number()
    .int('должна быть целым числом секунд')
    .min(0, 'не может быть отрицательной')
    .max(86_400, 'сутки записи — это ошибка, а не разговор'),

  /**
   * Размер выгруженного объекта в байтах.
   *
   * Больше нуля: пустой файл означает, что запись не состоялась, и принимать его
   * за состоявшуюся — значит потом не найти разговор, который считался сохранённым.
   */
  sizeBytes: z.coerce
    .number()
    .int('должен быть целым числом')
    .positive('пустой файл — это несостоявшаяся запись')
    .max(2_000_000_000, 'неправдоподобно большой файл'),
});

/**
 * Разовый доступ партнёра к записи
 * ([ADR-0036](../../../../../docs/adr/0036-dostup-partnyora-k-zapisyam.md)).
 *
 * Партнёр в запросе не называется: он выводится из вызова. Назвать его руками значит
 * однажды назвать не того и выдать чужой разговор.
 */
export const grantRecordingAccessSchema = z.object({
  /** Зачем открыт доступ: номер обращения, суть спора. Без причины доступ не выдаётся. */
  reason: z.string().trim().min(3, 'слишком короткая').max(500, 'слишком длинная'),
  /** Насколько открыт. Сутки по умолчанию, неделя — предел: дольше это уже не «разовый». */
  hours: z.coerce
    .number()
    .int('должно быть целым')
    .min(1, 'меньше часа')
    .max(168, 'дольше недели')
    .default(24),
});

/** Идентификаторы вызовов через запятую: одна страница списка в кабинете. */
export const availableQuerySchema = z.object({
  callIds: z
    .string()
    .transform((raw) => raw.split(',').filter((part) => part !== ''))
    .pipe(
      z
        .array(z.uuid('должны быть идентификаторами'))
        .min(1, 'нужен хотя бы один вызов')
        .max(50, 'не больше пятидесяти вызовов за раз'),
    ),
});
