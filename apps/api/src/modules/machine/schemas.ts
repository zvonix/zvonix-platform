/**
 * Схемы входных данных машинного доступа (ADR-0019).
 */

import { z } from 'zod';

/**
 * Адрес, с которого ключ принимается.
 *
 * Только точное совпадение: подсети сознательно не поддерживаются. Узел заводит
 * администратор, и его адрес известен поимённо, а разбор CIDR для IPv6 — это код,
 * ошибка в котором тихо расширяет список разрешённых. Понадобятся подсети —
 * добавить отдельно и с тестами.
 */
const ipAddress = z
  .union([z.ipv4(), z.ipv6()], { error: 'должен быть адресом IPv4 или IPv6' })
  .describe('адрес источника');

const label = z
  .string()
  .trim()
  .min(3, 'слишком короткое')
  .max(200, 'слишком длинное')
  .describe('назначение ключа: его читают через год, разбирая, что это');

export const issueNodeKeySchema = z.object({
  /** Узел, которому принадлежит ключ. */
  nodeId: z.uuid('должен быть идентификатором'),
  label,
  /**
   * У ключей узлов список положено заполнять: это единственная мера, работающая
   * и против кражи ключа с самого узла.
   */
  allowedIps: z.array(ipAddress).max(32, 'слишком много адресов').default([]),
});

export const issueClientKeySchema = z.object({
  clientId: z.uuid('должен быть идентификатором'),
  label,
  allowedIps: z.array(ipAddress).max(32, 'слишком много адресов').default([]),
});

/**
 * Ключ, который клиент заводит себе сам ([ADR-0044](../../../../../docs/adr/0044-klientskiy-api.md)).
 *
 * Идентификатора клиента здесь нет: он берётся из сессии — этим собственный контур
 * и отличается от административного выпуска.
 *
 * Список адресов и здесь необязателен: у клиента диспетчерская может стоять
 * за меняющимся адресом, и пустой список — осознанный выбор клиента, а не недосмотр.
 */
export const ownClientKeySchema = issueClientKeySchema.omit({ clientId: true });
