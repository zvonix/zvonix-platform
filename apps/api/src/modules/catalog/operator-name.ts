/**
 * Приведение названия оператора к сопоставимому виду.
 *
 * Одного и того же оператора внешние источники называют по-разному: файл плана
 * нумерации пишет `ООО "Сбербанк-Телеком"`, сервис определения отвечает
 * `Сбербанк-Телеком`, а люди говорят «СберМобайл». Сравнивать эти строки напрямую —
 * значит завести трёх операторов вместо одного и потерять определение на каждом.
 *
 * Приведённое написание хранится в `operator_aliases`; связь «написание → оператор»
 * задаёт администратор, а не догадка кода. Автоматически заводить оператора по
 * незнакомому названию нельзя: у оператора есть MNC, признак MVNO и хозяин сети,
 * и запись с пустыми значениями маршрутизация приняла бы за факт.
 */

/** Организационные формы, не несущие смысла при сопоставлении. */
const LEGAL_FORMS =
  /(^|\s)(ооо|оао|пао|зао|ао|ип|пк|нао|общество с ограниченной ответственностью|акционерное общество|публичное акционерное общество)(\s|$)/g;

/** Кавычки всех видов, встречающихся в русских выгрузках. */
const QUOTES = /["'«»“”„‟‘’]/g;

/**
 * Приводит название к виду, в котором его можно искать в справочнике.
 *
 * Буква «ё» заменяется на «е»: в выгрузках она пишется и так и так, и это единственное
 * различие, которое иначе даёт двух операторов с одинаковым названием.
 */
export function normalizeOperatorName(value: string): string {
  return value
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replace(QUOTES, ' ')
    .replace(LEGAL_FORMS, ' ')
    .replace(LEGAL_FORMS, ' ')
    .replace(/[.,]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
