/**
 * Разбор выгрузки плана нумерации (ADR-0032).
 *
 * Строки взяты из настоящего файла `DEF-9xx.csv` (2026-09-03), включая те, ради которых
 * замер и делался: составной регион в двух порядках и формат ГАР через вертикальную черту.
 */

import { describe, expect, it } from 'vitest';
import { DomainError } from '@zvonix/shared';
import { parseNumberingPlan } from './numbering-plan.js';

const HEADER = 'АВС/ DEF;От;До;Емкость;Оператор;Регион;Территория ГАР;ИНН';

const ROWS = [
  '900;0000000;0061999;62000;ООО "Т2 МОБАЙЛ";-;Краснодарский край;7743895280',
  '900;0062000;0062999;1000;ООО "Т2 МОБАЙЛ";-;Ростовская область;7743895280',
  '916;0000000;0999999;1000000;ПАО "МТС";-;Город Москва, Московская область;7740000076',
  '925;0000000;0099999;100000;ПАО "МТС";-;Московская область, Город Москва;7740000076',
  '999;9600000;9999999;400000;ООО "СИМ-СИМ";-;г. Норильск|г.о. город Норильск|Красноярский край;7701725181',
];

const FILE = [HEADER, ...ROWS].join('\n');

describe('разбор выгрузки', () => {
  it('читает строку целиком', () => {
    const { ranges } = parseNumberingPlan(FILE);

    expect(ranges[0]).toEqual({
      defCode: '900',
      // Границы — в том же виде, что и номер: код страны, DEF и семь цифр.
      rangeStart: 79_000_000_000n,
      rangeEnd: 79_000_061_999n,
      capacity: 62_000,
      operatorName: 'ООО "Т2 МОБАЙЛ"',
      inn: '7743895280',
      region: 'Краснодарский край',
    });
  });

  it('переживает BOM и переводы строк Windows', () => {
    // Файл отдаётся в UTF-8 с BOM, а через прокси может приехать с CRLF.
    const withBom = `\uFEFF${[HEADER, ...ROWS].join('\r\n')}\r\n`;
    expect(parseNumberingPlan(withBom).ranges).toHaveLength(ROWS.length);
  });

  it('берёт регион из «Территория ГАР», а не из «Регион»', () => {
    // В колонке «Регион» у 1 661 строки прочерк, а в «Территория ГАР» значение есть всегда.
    const { ranges } = parseNumberingPlan(FILE);
    expect(ranges.map((range) => range.region)).not.toContain('-');
    expect(ranges[2]?.region).toBe('Город Москва, Московская область');
  });

  it('сохраняет значение источника как есть, включая составные', () => {
    // Это и есть замер, ради которого ADR-0022 откладывал пересмотр: значение
    // не регион, а множество регионов в произвольном порядке. Приведение написаний
    // такое не сводит, и загрузчик не делает вид, что свёл.
    const { ranges } = parseNumberingPlan(FILE);
    expect(ranges[2]?.region).toBe('Город Москва, Московская область');
    expect(ranges[3]?.region).toBe('Московская область, Город Москва');
    expect(ranges[4]?.region).toContain('|');
  });
});

describe('негодный файл', () => {
  it('страница с ошибкой не разбирается в пустой план', () => {
    // Источник отдаёт её тем же кодом 200, и без этой проверки одна неудачная загрузка
    // стёрла бы план нумерации целиком.
    expect(() => parseNumberingPlan('<html><body>503</body></html>')).toThrow(DomainError);
  });

  it('называет причину доменной ошибкой, а не падением', () => {
    try {
      parseNumberingPlan('что угодно, только не выгрузка');
      expect.unreachable('разбор обязан отказать');
    } catch (cause) {
      expect(cause).toBeInstanceOf(DomainError);
      expect((cause as DomainError).code).toBe('dependency_unavailable');
    }
  });
});

describe('негодные строки', () => {
  const parseWith = (row: string) => parseNumberingPlan([HEADER, row].join('\n'));

  it('считает отброшенные, а не молчит о них', () => {
    // Рост этого числа — первый признак сменившегося формата, и он должен быть виден.
    const { ranges, skipped } = parseWith('900;0000000;0061999;62000;мало колонок');
    expect(ranges).toHaveLength(0);
    expect(skipped).toBe(1);
  });

  it('отбрасывает строку с нецифровым диапазоном', () => {
    expect(parseWith('900;абвгдеё;0061999;62000;ООО;-;Регион;7743895280').skipped).toBe(1);
  });

  it('отбрасывает строку с перевёрнутыми границами', () => {
    expect(parseWith('900;0062000;0061999;62000;ООО;-;Регион;7743895280').skipped).toBe(1);
  });

  it('отбрасывает строку, где ёмкость не сходится с шириной диапазона', () => {
    // Расхождение означает, что разобрано не то, а не что источник сообщил
    // дополнительный факт.
    expect(parseWith('900;0000000;0061999;7;ООО;-;Регион;7743895280').skipped).toBe(1);
  });

  it('отбрасывает строку без названия оператора', () => {
    expect(parseWith('900;0000000;0061999;62000; ;-;Регион;7743895280').skipped).toBe(1);
  });

  it('пустые строки не считаются отброшенными', () => {
    const { ranges, skipped } = parseNumberingPlan([HEADER, ROWS[0] ?? '', '', ''].join('\n'));
    expect(ranges).toHaveLength(1);
    expect(skipped).toBe(0);
  });
});
