/**
 * Схемы входных данных реестра узлов (ADR-0009).
 */

import { z } from 'zod';

const ipAddress = z.union([z.ipv4(), z.ipv6()], { error: 'должен быть адресом IPv4 или IPv6' });

export const provisionNodeSchema = z.object({
  /** Имя, по которому узел ищут в панели: «Москва-1». Уникально. */
  name: z.string().trim().min(2, 'слишком короткое').max(100, 'слишком длинное'),

  /**
   * Публичный адрес, на который партнёры направляют свои GOIP. Попадает в инструкцию
   * партнёру, поэтому это не тот адрес, с которого узел обращается к control plane.
   */
  sipAddress: z.string().trim().min(3, 'слишком короткий').max(200, 'слишком длинный').optional(),

  /**
   * Адреса, с которых принимается **токен установки**. Если адрес будущего узла известен
   * заранее — заполнить: токен живёт час, но ограничение по адресу закрывает и этот час.
   */
  allowedIps: z.array(ipAddress).max(8, 'слишком много адресов').default([]),
});

export const reissueInstallSchema = z.object({
  allowedIps: z.array(ipAddress).max(8, 'слишком много адресов').default([]),
});

export const enrollNodeSchema = z.object({
  /**
   * Имя машины. Приходит от узла и дальше сверяется с `hostname` в запросах маршрута:
   * расхождение означает, что ключ применён не на том узле, для которого выпущен.
   */
  hostname: z.string().trim().min(1, 'не может быть пустым').max(255, 'слишком длинное'),
  agentVersion: z.string().trim().max(50, 'слишком длинная').optional(),
});

/**
 * Пароль ESL узла ([ADR-0055](../../../../../docs/adr/0055-testovyy-zvonok-s-sim.md)).
 *
 * Установщик порождает его как 48 шестнадцатеричных знаков; шире — не наш установщик.
 * Адреса и порта здесь нет намеренно: площадка соединяется только с 127.0.0.1:8021,
 * иначе украденный ключ узла направлял бы её куда угодно.
 */
export const eslSchema = z.object({
  password: z
    .string()
    .regex(/^[0-9a-f]{32,128}$/, 'должен быть шестнадцатеричной строкой от 32 до 128 знаков'),
});

export const heartbeatSchema = z.object({
  /** Активных вызовов на момент отправки. */
  activeCalls: z.coerce
    .number()
    .int('должно быть целым числом')
    .min(0, 'не может быть отрицательным')
    .max(100_000, 'неправдоподобно много')
    .default(0),

  /**
   * Узел сам сообщает, считает ли себя ослабленным: часть шлюзов не зарегистрирована,
   * нагрузка выше порога. Решение «жив или нет» остаётся за control plane — молчание
   * снимает узел с маршрутизации независимо от того, что он присылал раньше.
   */
  degraded: z.boolean().default(false),

  agentVersion: z.string().trim().max(50, 'слишком длинная').optional(),
});
