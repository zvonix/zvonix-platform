'use client';

import { useSession } from './session';

/**
 * Может ли вошедший что-то менять, или он здесь только смотрит.
 *
 * Правило зеркалит контракт API: изменяющие обработчики помечены `@Roles('admin')`,
 * читающие — `@Roles('admin', 'support')`
 * ([ADR-0018](../../../../docs/adr/0018-autentifikaciya.md)). То есть у поддержки есть
 * право видеть почти всё и нет права трогать ничего.
 *
 * **Это не рубеж, а вежливость.** Настоящая проверка одна, и она в API: кнопка,
 * спрятанная в браузере, никого не останавливает. Смысл в другом — нарисованная
 * кнопка, которая отвечает `403`, обещает возможность, которой нет, и человек ищет
 * причину в себе.
 *
 * Роль берётся из ответа `/auth/me`, а не из хранилища браузера: сессия лежит
 * в cookie с `HttpOnly` ([ADR-0037](../../../../docs/adr/0037-sessiya-v-brauzere.md)),
 * и вычитанная из хранилища роль — то, что подделывается в консоли за десять секунд.
 * Запрос общий с `useSession`, второго обращения не будет.
 */
export function useCanChange(): boolean {
  return useSession().data?.role === 'admin';
}
