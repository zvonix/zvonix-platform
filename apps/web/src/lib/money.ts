/**
 * Показ денег — и обратный перевод набранного человеком.
 *
 * API отдаёт сумму **строкой** — `"1500.5"`. Не числом: `0.1 + 0.2` в двоичной
 * плавающей точке не равно `0.3`, и копейки теряются молча. Кабинет эту строку
 * не разбирает и не считает — только показывает.
 *
 * [DESIGN.md](../../../../docs/DESIGN.md): деньги всегда с явной валютой и никогда
 * не округляются молча. Если у суммы есть дробная часть, она видна.
 */

/**
 * Пробелы заданы escape-последовательностями намеренно.
 *
 * Оба неразрывные, и в исходном тексте они неотличимы от обычного пробела: строка
 * выглядит правильно, сравнение в проверке — нет, и полдня уходит на «одинаковые
 * строки не равны». Записанные явно, они видны и в коде, и в тестах.
 */
const NARROW_NO_BREAK = '\u202F';
const NO_BREAK = '\u00A0';

/** Валюта одна ([ADR-0010](../../../../docs/adr/0010-model-billinga.md)). */
const CURRENCY = `${NO_BREAK}₽`;

/**
 * Разряды разделяются, дробная часть остаётся как есть.
 *
 * `Intl` здесь не годится: он принимает число, а число — ровно то, чего мы избегаем.
 * Поэтому разбор строки, а не преобразование.
 */
export function money(value: string): string {
  const match = /^(-?)(\d+)(?:\.(\d+))?$/.exec(value.trim());
  // Не сумма — показываем как есть. Молча подставить ноль было бы хуже:
  // на экране денег неверное число опаснее непонятного.
  if (match === null) return value;

  const [, sign = '', whole = '0', fraction] = match;
  const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, NARROW_NO_BREAK);
  const tail = fraction === undefined ? '' : `,${fraction}`;
  return `${sign}${grouped}${tail}${CURRENCY}`;
}

/** Отрицательная сумма? Нужно, чтобы выделить долг, не разбирая строку дважды. */
export function isNegative(value: string): boolean {
  return value.trim().startsWith('-');
}

/**
 * Доля в десятитысячных — процентом, как её называет человек.
 *
 * API отдаёт `1500`, договорённость с партнёром звучит «пятнадцать процентов».
 * Показывать базисные пункты значит требовать деления в уме на каждом экране.
 * Дробная часть остаётся, если она есть: `1525` — это 15,25 %, а не 15 %.
 */
export function percent(basisPoints: string): string {
  const parsed = Number(basisPoints.trim());
  if (!Number.isFinite(parsed)) return basisPoints;

  const value = parsed / 100;
  return `${String(value).replace('.', ',')}${NO_BREAK}%`;
}

/**
 * Число, как его набрал человек, — в тот вид, который принимает API.
 *
 * Кабинет показывает деньги с запятой (`money` выше), и на русской раскладке запятая
 * же и набирается. API принимает **только точку**: это машинный формат, общий
 * с узлом и CDR ([ADR-0010](../../../../docs/adr/0010-model-billinga.md)), и менять его
 * ради удобства ввода нельзя. Значит перевод делает кабинет — тот, кто знает,
 * что перед ним человек.
 *
 * Убираются заодно пробелы и знаки `₽` и `%`: строку вида `1 500,5 ₽` человек копирует
 * из соседней таблицы этого же кабинета, и отказывать ему в его же выводе странно.
 * `\s` покрывает и неразрывные пробелы, которыми `money` разделяет разряды.
 *
 * Один разбор на все формы намеренно: до него перевод делала одна форма из семи,
 * а остальные шесть отвечали «данные не прошли проверку» на `0,1`.
 */
export function numberFromInput(value: string): string {
  return value.replace(/[\s₽%]/gu, '').replace(',', '.');
}
