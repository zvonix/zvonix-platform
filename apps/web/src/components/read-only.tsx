'use client';

/**
 * Отметка «здесь только смотрят».
 *
 * Ставится там, где у роли есть право видеть раздел и нет права его менять.
 * Без неё отсутствие кнопок читается как неисправность: человек ищет, куда нажать,
 * и не находит — а причина в его роли, и сказать об этом должен экран, а не догадка.
 */
export function ReadOnly({ what }: { what: string }) {
  return <p className="text-muted-foreground">Только чтение: {what} меняет администратор.</p>;
}
