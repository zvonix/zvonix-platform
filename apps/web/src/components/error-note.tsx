'use client';

import type { ApiError } from '@/lib/api';

/**
 * Отказ API так, как его показывают человеку.
 *
 * Вместе с сообщением показываются **разборы по полям** (`problems`): без них форма
 * отвечает «Данные запроса не прошли проверку» и не говорит, какое поле и чем не годится.
 * Человек тогда перебирает поля вслепую — и именно так пропускается опечатка вроде
 * запятой там, где ждут точку.
 *
 * Отдельным куском, а не строкой в каждой форме: одинаковых копий этой разметки было
 * четыре, и ещё в пяти формах разбор по полям просто не показывался. Расхождение такого
 * рода не ловится ничем, кроме случайной встречи с ним.
 */
export function ErrorNote({ error, className = '' }: { error: ApiError; className?: string }) {
  return (
    <p role="alert" className={`text-crit ${className}`.trim()}>
      {error.message}
      {error.problems.length > 0 && ` — ${error.problems.join('; ')}`}
    </p>
  );
}
