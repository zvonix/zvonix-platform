/**
 * Регион как множество субъектов (ADR-0033).
 *
 * Значения взяты из настоящего файла плана нумерации: составные в обоих порядках,
 * официальные названия с альтернативным именем через тире, иерархия ГАР.
 */

import { describe, expect, it } from 'vitest';
import { regionKeyOf, regionKeysOf } from './region.js';

describe('приведение написания', () => {
  it.each([
    ['Красноярский край', 'красноярский'],
    ['Красноярский кр.', 'красноярский'],
    ['КРАСНОЯРСКИЙ КРАЙ', 'красноярский'],
    ['  Красноярский   край  ', 'красноярский'],
    ['Новосибирская область', 'новосибирская'],
    ['Новосибирская обл.', 'новосибирская'],
    ['г. Москва', 'москва'],
    ['Москва', 'москва'],
    ['Республика Татарстан', 'татарстан'],
    ['Респ. Татарстан', 'татарстан'],
    ['Татарстан', 'татарстан'],
    ['Ямало-Ненецкий АО', 'ямало-ненецкий'],
    ['Ямало-Ненецкий автономный округ', 'ямало-ненецкий'],
    ['Еврейская автономная область', 'еврейская'],
    ['Тюменская обл', 'тюменская'],
  ])('%s → %s', (input, expected) => {
    expect(regionKeyOf(input)).toBe(expected);
  });

  it('все написания одного региона дают один ключ', () => {
    // Иначе партнёр объявляет покрытие, вызовов не получает, и понять почему нельзя:
    // отказ выглядит как 503 и молчание.
    const forms = ['Красноярский край', 'Красноярский кр.', 'красноярский КРАЙ'];
    expect(new Set(forms.map(regionKeyOf)).size).toBe(1);
  });

  it('не склеивает разные регионы', () => {
    const keys = [
      'Москва',
      'Московская область',
      'Ростовская область',
      'Ленинградская область',
      'Санкт-Петербург',
    ].map(regionKeyOf);
    expect(new Set(keys).size).toBe(keys.length);
  });

  it('дефис внутри слова сохраняется', () => {
    // `ханты-мансийский` — одно слово, и разрыв его превратил бы регион в другой.
    expect(regionKeyOf('Ханты-Мансийский АО')).toBe('ханты-мансийский');
  });

  it('«ё» и «е» дают один ключ', () => {
    expect(regionKeyOf('Орёл')).toBe(regionKeyOf('Орел'));
  });

  it('строка из одних служебных слов региона не называет', () => {
    // Пустой ключ совпал бы с другим пустым и связал два разных региона.
    expect(regionKeysOf('область')).toEqual([]);
    expect(regionKeyOf('область')).toBeNull();
    expect(regionKeyOf('  ')).toBeNull();
    expect(regionKeyOf(null)).toBeNull();
    expect(regionKeyOf(undefined)).toBeNull();
  });
});

describe('перечисление субъектов', () => {
  it('порядок перечисления ничего не меняет', () => {
    // 1042 диапазона написаны в одном порядке и 75 — в обратном. Приведение целой
    // строки давало два разных ключа, и ни один не совпадал с «Москва».
    expect(regionKeysOf('Город Москва, Московская область')).toEqual(['москва', 'московская']);
    expect(regionKeysOf('Московская область, Город Москва')).toEqual(['московская', 'москва']);

    const straight = new Set(regionKeysOf('Город Москва, Московская область'));
    const reversed = new Set(regionKeysOf('Московская область, Город Москва'));
    expect(straight).toEqual(reversed);
  });

  it('оба субъекта пары становятся ключами', () => {
    expect(regionKeysOf('Город Санкт-Петербург, Ленинградская область')).toEqual([
      'санкт-петербург',
      'ленинградская',
    ]);
    expect(regionKeysOf('Архангельская область, Ненецкий автономный округ')).toEqual([
      'архангельская',
      'ненецкий',
    ]);
  });

  it('основным становится первый', () => {
    expect(regionKeyOf('Город Москва, Московская область')).toBe('москва');
  });
});

describe('альтернативное имя субъекта через тире', () => {
  it.each([
    ['Кемеровская область - Кузбасс', ['кемеровская', 'кузбасс']],
    ['Ханты-Мансийский автономный округ - Югра', ['ханты-мансийский', 'югра']],
    ['Чувашская Республика - Чувашия', ['чувашская', 'чувашия']],
    ['Республика Северная Осетия - Алания', ['северная осетия', 'алания']],
  ])('%s → оба имени', (input, expected) => {
    // Официальное название содержит два имени одного субъекта. Склеенные в один ключ,
    // они не совпадали ни с одним написанием партнёра — 595 диапазонов мимо.
    expect(regionKeysOf(input)).toEqual(expected);
  });

  it('партнёр совпадает любым из двух имён', () => {
    const range = regionKeysOf('Кемеровская область - Кузбасс');
    expect(range).toContain(regionKeyOf('Кемеровская область'));
    expect(range).toContain(regionKeyOf('Кузбасс'));
  });

  it('длинное тире и короткое работают одинаково', () => {
    expect(regionKeysOf('Ханты-Мансийский АО — Югра')).toEqual(['ханты-мансийский', 'югра']);
  });
});

describe('иерархия ГАР', () => {
  it('берётся самый широкий уровень — субъект', () => {
    // Перечисление идёт от узкого к широкому. Город и муниципалитет ключами
    // не становятся: покрытие объявляется субъектами.
    expect(regionKeysOf('г. Норильск|г.о. город Норильск|Красноярский край')).toEqual([
      'красноярский',
    ]);
    expect(regionKeysOf('г. Псков|г.о. город Псков|Псковская область')).toEqual(['псковская']);
  });
});

describe('страна регионом не считается', () => {
  it.each(['Российская Федерация', 'Россия', 'РФ'])('%s → региона нет', (input) => {
    // 37 диапазонов выделены на всю страну. Считать это регионом значило бы завести
    // субъект, которого никто никогда не объявит в покрытии.
    expect(regionKeysOf(input)).toEqual([]);
    expect(regionKeyOf(input)).toBeNull();
  });
});
