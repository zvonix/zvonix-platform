import { describe, expect, it } from 'vitest';
import { normalizeRegion } from './region.js';

describe('приведение названия региона к ключу', () => {
  it.each([
    ['Красноярский край', 'красноярский'],
    ['Красноярский кр.', 'красноярский'],
    ['КРАСНОЯРСКИЙ КРАЙ', 'красноярский'],
    ['  Красноярский   край  ', 'красноярский'],
    ['Новосибирская область', 'новосибирская'],
    ['Новосибирская обл.', 'новосибирская'],
    ['г. Москва', 'москва'],
    ['Москва', 'москва'],
    ['Республика Татарстан', 'татарстан'],
    ['Респ. Татарстан', 'татарстан'],
    ['Татарстан', 'татарстан'],
    ['Ямало-Ненецкий АО', 'ямало-ненецкий'],
    ['Ямало-Ненецкий автономный округ', 'ямало-ненецкий'],
    ['Еврейская автономная область', 'еврейская'],
    ['Тюменская обл', 'тюменская'],
  ])('%s → %s', (input, expected) => {
    expect(normalizeRegion(input)).toBe(expected);
  });

  it('все написания одного региона дают один ключ', () => {
    // Иначе партнёр объявляет покрытие, вызовов не получает, и понять почему нельзя:
    // отказ выглядит как 503 и молчание.
    const forms = ['Красноярский край', 'Красноярский кр.', 'красноярский КРАЙ'];
    expect(new Set(forms.map(normalizeRegion)).size).toBe(1);
  });

  it('не склеивает разные регионы', () => {
    const keys = [
      'Москва',
      'Московская область',
      'Ростовская область',
      'Ленинградская область',
      'Санкт-Петербург',
    ].map(normalizeRegion);
    expect(new Set(keys).size).toBe(keys.length);
  });

  it('дефис внутри слова сохраняется, тире между словами — нет', () => {
    // `ханты-мансийский` — одно слово, и разрыв его превратил бы регион в другой.
    expect(normalizeRegion('Ханты-Мансийский АО')).toBe('ханты-мансийский');
    expect(normalizeRegion('Ханты-Мансийский АО — Югра')).toBe('ханты-мансийский югра');
  });

  it('«ё» и «е» дают один ключ', () => {
    expect(normalizeRegion('Орёл')).toBe(normalizeRegion('Орел'));
  });

  it('строка из одних служебных слов даёт пустой ключ', () => {
    // Вызывающий обязан такой ключ отвергнуть: пустой совпал бы с другим пустым
    // и связал два разных региона.
    expect(normalizeRegion('область')).toBe('');
    expect(normalizeRegion('  ')).toBe('');
  });
});
