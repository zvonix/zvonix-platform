/**
 * Идентификаторы сущностей.
 *
 * UUIDv7 (см. «Идентификаторы» в docs/DOMAIN.md): генерируются приложением до записи
 * в базу — это нужно для идемпотентности, — монотонны по времени и потому не разрушают
 * локальность индекса, и не раскрывают объём бизнеса, как автоинкремент.
 *
 * Тип параметризован именем сущности. `UserId` и `PartnerId` — оба строки, но разные типы,
 * поэтому перепутать их местами в вызове нельзя: в системе, где почти у каждой таблицы
 * есть ссылка на две-три другие, это самая частая ошибка, которую компилятор способен поймать.
 * Для колонок Drizzle приводить вручную не нужно — там есть `.$type<...>()`.
 */

import { v7 as uuidV7 } from 'uuid';
import { validationFailed } from './errors.js';

declare const idBrand: unique symbol;

/** Идентификатор сущности `T`. Внутри — строка UUID, но присвоить произвольную строку нельзя. */
export type Id<T extends string> = string & { readonly [idBrand]: T };

/**
 * Формат UUID любой версии в каноническом виде.
 * Версию отдельно не проверяем: в базе уже могут оказаться идентификаторы,
 * пришедшие из внешних систем, а формат гарантирует главное — что это UUID.
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Новый идентификатор. Вызывается в приложении, а не в базе. */
export function newId<T extends string>(): Id<T> {
  return uuidV7() as Id<T>;
}

/** Проверка формата без приведения типа. */
export function isId(value: unknown): value is string {
  return typeof value === 'string' && UUID.test(value);
}

/**
 * Разбор идентификатора, пришедшего снаружи: из параметра запроса, тела, очереди.
 * Непрошедшее значение — ошибка валидации, а не исключение общего вида.
 */
export function parseId<T extends string>(value: unknown, entity: T): Id<T> {
  if (!isId(value)) {
    throw validationFailed('Некорректный идентификатор', { details: { entity } });
  }
  return value.toLowerCase() as Id<T>;
}
