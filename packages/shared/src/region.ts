/**
 * Приведение названия региона к сопоставимому виду ([ADR-0022](../../../docs/adr/0022-pokrytie-regionov.md)).
 *
 * Регион приходит текстом из внешних источников и пишется по-разному: `Красноярский край`,
 * `Красноярский кр.`, `КРАСНОЯРСКИЙ КРАЙ`. Сравнивать эти строки напрямую — значит
 * отказывать в вызовах партнёру, который регион объявил: покрытие не совпадёт, а отказ
 * будет выглядеть как `503` и молчание.
 *
 * Приём тот же, что и у названий операторов (`normalizeOperatorName`): из ключа убирается
 * всё, что не различает регионы, — регистр, `ё`, знаки препинания и слова вида «область»,
 * «край», «республика», «АО». Остаётся различающая часть.
 *
 * Чего этот приём не умеет: написания, различающиеся не окончанием, а составом
 * (`Ханты-Мансийский АО` и `Ханты-Мансийский автономный округ — Югра`), дают разные ключи.
 * Это случай для справочника регионов с синонимами, а не для правила; условие его
 * появления названо в ADR-0022.
 */

/**
 * Слова, обозначающие тип субъекта, а не сам субъект.
 *
 * Длинные сочетания идут первыми: «автономный округ» должен сработать раньше, чем «округ»,
 * иначе от него останется висящее «автономный».
 */
const REGION_TYPES =
  /(^|\s)(автономный округ|автономная область|автономного округа|область|обл|края|край|кр|республики|республика|респ|округ|окр|города|город|район|р-н|ао|г)(\s|$)/g;

/** Кавычки всех видов, встречающихся в русских выгрузках. */
const QUOTES = /["'«»“”„‟‘’]/g;

/** Тире между словами: `Ханты-Мансийский АО — Югра`. Дефис внутри слова обязан уцелеть. */
const STANDALONE_DASHES = /(^|\s)[-–—]+(\s|$)/g;

/**
 * Приводит название региона к ключу, по которому регионы сравниваются.
 *
 * Возвращает пустую строку, если после приведения не осталось ничего: строка вроде
 * «область» региона не называет. Вызывающий обязан такой ключ отвергнуть, а не сохранить —
 * пустой ключ совпал бы с другим пустым и связал два разных региона.
 */
export function normalizeRegion(value: string): string {
  return (
    value
      .toLowerCase()
      .replaceAll('ё', 'е')
      .replace(QUOTES, ' ')
      .replace(/[.,()]/g, ' ')
      .replace(STANDALONE_DASHES, ' ')
      .replace(STANDALONE_DASHES, ' ')
      // Дважды: соседние слова делят между собой пробел, и первое совпадение съедает
      // разделитель, нужный второму. Та же причина, что и в `normalizeOperatorName`.
      .replace(REGION_TYPES, ' ')
      .replace(REGION_TYPES, ' ')
      .replace(/\s+/g, ' ')
      .trim()
  );
}

/**
 * Ключ региона или `null` — «региона нет».
 *
 * Одна функция на всех, кто сравнивает регионы: покрытие партнёра, цена партнёра
 * и коридор цен. Пустой результат приведения означает, что строка региона не называет
 * («область», «край»), и такой ключ хранить нельзя — он совпал бы с другим пустым.
 */
export function regionKeyOf(value: string | null | undefined): string | null {
  if (value === null || value === undefined) return null;
  const key = normalizeRegion(value);
  return key === '' ? null : key;
}
