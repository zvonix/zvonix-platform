/**
 * Регион как множество субъектов ([ADR-0033](../../../docs/adr/0033-region-eto-mnozhestvo.md),
 * уточняет [ADR-0022](../../../docs/adr/0022-pokrytie-regionov.md)).
 *
 * Регион приходит текстом из внешних источников, и в нём две разные беды.
 *
 * **Написание.** `Красноярский край`, `Красноярский кр.`, `КРАСНОЯРСКИЙ КРАЙ` — один
 * регион. Сравнивать эти строки напрямую значит отказывать в вызовах партнёру, который
 * регион объявил: покрытие не совпадёт, а отказ будет выглядеть как `503` и молчание.
 * Лечится приведением — тем же приёмом, что и у названий операторов
 * (`normalizeOperatorName`): из ключа убирается всё, что не различает регионы.
 *
 * **Перечисление.** Значение часто называет не один субъект, а несколько:
 * `Город Москва, Московская область` — и в обратном порядке тоже. Замер на плане
 * нумерации: каждый седьмой диапазон из 17 060. Приведение целой строки такое не сводит
 * — получаются два разных ключа, и ни один не совпадает с «Москва». Лечится разбиением
 * на множество: два порядка дают одинаковый набор, и вопрос порядка исчезает.
 */

/**
 * Слова, обозначающие тип субъекта, а не сам субъект.
 *
 * Длинные сочетания идут первыми: «автономный округ» должен сработать раньше, чем «округ»,
 * иначе от него останется висящее «автономный».
 */
const REGION_TYPES =
  /(^|\s)(автономный округ|автономная область|автономного округа|область|обл|края|край|кр|республики|республика|респ|округ|окр|города|город|район|р-н|ао|г)(\s|$)/g;

/** Кавычки всех видов, встречающихся в русских выгрузках. */
const QUOTES = /["'«»“”„‟‘’]/g;

/**
 * Тире между словами: `Ханты-Мансийский АО — Югра`. Дефис внутри слова обязан уцелеть.
 *
 * В официальных названиях четырёх субъектов тире отделяет **альтернативное имя того же
 * субъекта**: Кузбасс, Югра, Чувашия, Алания. Поэтому части по обе стороны тире —
 * не разные регионы, а два имени одного, и оба становятся ключами.
 */
const STANDALONE_DASH = /(?:^|\s)[-–—]+(?:\s|$)/;

/**
 * Названия страны в приведённом виде.
 *
 * `Российская Федерация` стоит у 37 диапазонов плана нумерации и означает не регион,
 * а его отсутствие: ёмкость выделена на всю страну. Считать это регионом значило бы
 * завести субъект, которого никто никогда не объявит в покрытии.
 */
const COUNTRY_NAMES = new Set(['российская федерация', 'россия', 'рф']);

/**
 * Приводит написание одного субъекта к ключу.
 *
 * Возвращает пустую строку, если после приведения не осталось ничего: строка вроде
 * «область» региона не называет.
 */
function normalizeRegion(value: string): string {
  return (
    value
      .toLowerCase()
      .replaceAll('ё', 'е')
      .replace(QUOTES, ' ')
      .replace(/[.,()]/g, ' ')
      // Дважды: соседние слова делят между собой пробел, и первое совпадение съедает
      // разделитель, нужный второму. Та же причина, что и в `normalizeOperatorName`.
      .replace(REGION_TYPES, ' ')
      .replace(REGION_TYPES, ' ')
      .replace(/\s+/g, ' ')
      .trim()
  );
}

/**
 * Ключи всех субъектов, названных строкой. Пустой набор — «региона нет».
 *
 * **Одна функция на всех, кто сравнивает регионы:** покрытие партнёра, цена партнёра
 * и коридор цен. Две разные реализации разъедутся, и не поймает этого ни один тест
 * ниже сквозного (ADR-0033).
 *
 * Разделители значат разное, поэтому и обрабатываются по-разному:
 *
 * | Разделитель | Что означает | Что делаем |
 * |---|---|---|
 * | `\|` | иерархия ГАР от узкого к широкому: `г. Норильск\|г.о. город Норильск\|Красноярский край` | берём последний — субъект |
 * | `,` | перечисление субъектов: `Город Москва, Московская область` | все становятся ключами |
 * | тире между словами | альтернативное имя субъекта: `Кемеровская область - Кузбасс` | оба становятся ключами |
 *
 * Порядок сохраняется — по нему выбирается основной ключ хранимой строки, — но на
 * сравнение не влияет: сравнение идёт пересечением наборов.
 */
export function regionKeysOf(value: string | null | undefined): string[] {
  if (value === null || value === undefined) return [];

  // Иерархия ГАР перечисляет место от узкого к широкому, и субъект в ней последний.
  // Город и муниципалитет ключами не становятся: покрытие объявляется субъектами.
  const widest = value.split('|').at(-1) ?? '';

  const keys: string[] = [];
  for (const subject of widest.split(',')) {
    for (const spelling of subject.split(STANDALONE_DASH)) {
      const key = normalizeRegion(spelling);
      // Пустой ключ хранить нельзя: он совпал бы с другим пустым и связал два разных
      // региона. Название страны — не регион, а его отсутствие.
      if (key === '' || COUNTRY_NAMES.has(key)) continue;
      if (!keys.includes(key)) keys.push(key);
    }
  }
  return keys;
}

/**
 * Основной ключ строки — первый из набора, или `null`, если региона в ней нет.
 *
 * Нужен там, где регион **хранится**: у строки покрытия, цены и коридора ключ один.
 * Партнёр, написавший официальное «Кемеровская область - Кузбасс», сохранит
 * `кемеровская` — и совпадёт с набором диапазона `{кемеровская, кузбасс}`.
 * Написавший «Кузбасс» совпадёт тоже: сравнение идёт пересечением (ADR-0033).
 */
export function regionKeyOf(value: string | null | undefined): string | null {
  return regionKeysOf(value)[0] ?? null;
}
