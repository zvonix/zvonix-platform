/**
 * Вызов и резерв средств под него (ADR-0010, DOMAIN.md).
 */

import type { DialledNumber, Msisdn } from './msisdn.js';

/**
 * Что стоит в назначении вызова.
 *
 * Канонический номер — везде, кроме отказа `destination_invalid`: там записываются
 * цифры набранного, потому что иначе причине отказа не к чему относиться
 * ([ADR-0042](../../../docs/adr/0042-diagnoz-po-nerazobrannomu-nomeru.md)).
 * Тип объединяющий, но не `string`: в назначение попадает только то, что прошло
 * разбор — либо приведение к каноническому виду, либо отбор цифр.
 */
export type CallDestination = Msisdn | DialledNumber;

/**
 * Состояние попытки вызова.
 *
 * `routing`   — маршрут запрошен, решение принимается;
 * `ringing`   — узел дозванивается по выданным кандидатам;
 * `answered`  — соединение установлено, идёт разговор;
 * `completed` — разговор завершён нормально. **Тарифицируются только такие**;
 * `failed`    — вызов не состоялся. Причина в `failure_reason`;
 * `no_answer` — не ответили;
 * `busy`      — занято;
 * `cancelled` — вызывающий положил трубку до ответа.
 *
 * Отказ маршрутизации — это тоже вызов, со статусом `failed` и причиной. Иначе
 * на вопрос «почему у клиента не звонит» отвечать нечем: в журнале ничего не остаётся.
 */
export const CALL_STATUSES = [
  'routing',
  'ringing',
  'answered',
  'completed',
  'failed',
  'no_answer',
  'busy',
  'cancelled',
] as const;
export type CallStatus = (typeof CALL_STATUSES)[number];

/**
 * Состояния, в которых вызов занимает ресурс: SIM и зарезервированные деньги.
 *
 * По ним считается одновременность на SIM. `routing` входит намеренно: между выдачей
 * маршрута и первым гудком проходит время, и если в этот промежуток SIM считается
 * свободной, на неё уйдёт второй вызов.
 */
export const OPEN_CALL_STATUSES: readonly CallStatus[] = ['routing', 'ringing', 'answered'];

export function isOpenCall(status: CallStatus): boolean {
  return OPEN_CALL_STATUSES.includes(status);
}

/** Тарифицируется только завершённый разговор (DOMAIN.md). */
export function isBillableCall(status: CallStatus): boolean {
  return status === 'completed';
}

/**
 * Причина, по которой вызов не состоялся.
 *
 * Значения совпадают с теми, что уходят в переменную `zvonix_reject_reason` на узле
 * и возвращаются обратно в CDR (docs/api/node.md). Абонент видит грубый код SIP,
 * поддержка — точную причину: сообщать звонящему, что у клиента кончились деньги,
 * не следует.
 */
export const CALL_FAILURE_REASONS = [
  /** Канал неизвестен, не активен либо закрыт доступ клиенту. */
  'channel_unknown',
  /**
   * Набранное не приводится к российскому номеру: короткий, экстренный, служебный
   * либо вовсе не номер.
   *
   * Отдельно от `operator_unconfirmed`: до определения оператора такой вызов
   * не доходит, и разбирать резолвер по нему — ложный след
   * ([ADR-0042](../../../docs/adr/0042-diagnoz-po-nerazobrannomu-nomeru.md)).
   * Отдельного кода для экстренных номеров нет намеренно: он требует их списка,
   * а угаданный список запретов — это неработающая телефония (ADR-0024, §4).
   */
  'destination_invalid',
  /** Оператор номера не подтверждён. Гадать запрещено (ADR-0013). */
  'operator_unconfirmed',
  /** Номер в чёрном списке. */
  'destination_blocked',
  /**
   * Оператор номера не входит в список разрешённых для канала.
   *
   * Отдельно от `destination_blocked`: запрет платформы клиент не снимет, а свою
   * настройку меняет сам — это два разных разговора (ADR-0025).
   */
  'operator_not_allowed',
  /** Нет действующего тарифа партнёра по направлению или правила наценки. */
  'no_tariff',
  /** Овердрафт исчерпан: средств не хватает даже на резерв. */
  'insufficient_funds',
  /** Исчерпано окно лимита. */
  'limit_exceeded',
  /** Нет свободной SIM нужного оператора. */
  'no_sim_available',
  /**
   * Годная SIM есть, но её шлюз не зарегистрирован на узле, принявшем вызов.
   *
   * Отдельно от `no_sim_available`: там разговор с партнёром о том, что SIM нет вовсе,
   * здесь — о том, что железо не на связи. Вызов через незарегистрированный шлюз
   * не набрать: диалплан обращается к нему как к зарегистрированному пользователю,
   * и на чужом узле такой записи нет.
   */
  'gateway_unregistered',
  /** Канал требует запись, а подходят только шлюзы, где она невозможна. */
  'recording_required',
  /** Регион номера не покрыт ни одним партнёром. */
  'no_coverage',
  /**
   * Узел не прислал CDR: вызов провисел открытым дольше предельной длительности.
   *
   * Отдельная причина, а не общая внутренняя ошибка: для поддержки это диагноз узла,
   * а не платформы, и рост числа таких вызовов означает, что с узлом что-то не так.
   */
  'node_lost',
  /** Внутренняя неисправность control plane. */
  'internal_error',
] as const;
export type CallFailureReason = (typeof CALL_FAILURE_REASONS)[number];

/**
 * Причина отказа так, как её видит **клиент**.
 *
 * Набор уже внутреннего намеренно. Часть причин клиенту адресована прямо — кончились
 * деньги, исчерпан его лимит, оператор не разрешён его же настройкой, номер запрещён
 * площадкой. Остальные говорят о нашей стороне: нет свободной SIM, регион не покрыт,
 * не задана цена, узел молчит. Их точная формулировка — сведения о ёмкости площадки,
 * и клиент по ним читал бы, сколько у нас SIM и где мы их не держим.
 *
 * Поэтому всё, что не относится к самому клиенту, схлопывается в `platform`: это
 * не сокрытие неисправности — факт отказа виден, — а отказ обсуждать с клиентом
 * устройство нашей стороны ([ADR-0014](../../../docs/adr/0014-vybor-partnera-klientom.md)
 * держит ту же границу для личности партнёра).
 */
export const CLIENT_FAILURE_REASONS = [
  /** Номер запрещён площадкой. */
  'destination_blocked',
  /** Набранное не похоже на российский номер: короткий, экстренный или служебный. */
  'destination_invalid',
  /** Оператор номера не подтверждён: звонить, не зная оператора, платформа не станет. */
  'operator_unconfirmed',
  /** Оператор не входит в список, разрешённый каналом. Настройка самого клиента. */
  'operator_not_allowed',
  /** Не хватает денег даже на резерв под вызов. */
  'insufficient_funds',
  /** Исчерпано окно лимита клиента или канала. */
  'limit_exceeded',
  /** Отказ на нашей стороне. Подробности — у поддержки, а не в ответе API. */
  'platform',
] as const;
export type ClientFailureReason = (typeof CLIENT_FAILURE_REASONS)[number];

/** Причины, которые клиенту показываются как есть: они про него, а не про площадку. */
const CLIENT_VISIBLE_REASONS: readonly CallFailureReason[] = [
  'destination_blocked',
  'destination_invalid',
  'operator_unconfirmed',
  'operator_not_allowed',
  'insufficient_funds',
  'limit_exceeded',
];

/**
 * Перевод причины отказа в клиентский контур.
 *
 * Список `CLIENT_VISIBLE_REASONS` перечислен явно, а не выведен вычитанием: новая
 * внутренняя причина обязана по умолчанию оказаться скрытой, а не показанной клиенту
 * из-за того, что её забыли внести в список исключений.
 */
export function clientFailureReasonOf(reason: CallFailureReason): ClientFailureReason {
  return CLIENT_VISIBLE_REASONS.includes(reason) ? (reason as ClientFailureReason) : 'platform';
}

/**
 * Состояние резерва (ADR-0010).
 *
 * `held`     — средства придержаны на время вызова;
 * `captured` — вызов завершён, списана фактическая сумма;
 * `released` — вызов не состоялся или резерв истёк, средства освобождены.
 *
 * Из `captured` и `released` не возвращаются: резерв закрывается ровно один раз.
 */
export const RESERVATION_STATUSES = ['held', 'captured', 'released'] as const;
export type ReservationStatus = (typeof RESERVATION_STATUSES)[number];
