/**
 * Перечисления справочника операторов (ADR-0013).
 *
 * Отдельно от `enums.ts` с учётными записями: разные области домена, и смешивать
 * их в одном файле — верный способ получить список, в который заглядывают все и правит
 * кто угодно.
 */

/**
 * Откуда взят план нумерации.
 *
 * Источников намеренно два, и они не заменяют друг друга: у НИЦ Телеком есть MNC
 * и маршрутный номер, у Минцифры — ИНН и DEF-коды 954, 955, 970, 971, 997,
 * которых у первого нет. Сливаются по ИНН оператора.
 */
export const NUMBERING_PLAN_SOURCES = ['nic_t', 'mincifry'] as const;
export type NumberingPlanSource = (typeof NUMBERING_PLAN_SOURCES)[number];

/**
 * Чем определён оператор конкретного номера.
 *
 * Записывается в CDR: без этого разобрать спор о цене вызова невозможно —
 * непонятно, был ответ авторитетным или выведен из диапазона.
 *
 * `numbering_plan` — самый слабый: он говорит, кому диапазон **выделен**, а не кто
 * обслуживает номер сейчас. Для перенесённого номера это неверный ответ, поэтому
 * такое разрешение не считается подтверждённым.
 */
export const RESOLUTION_SOURCES = ['lookup', 'numbering_plan', 'manual'] as const;
export type ResolutionSource = (typeof RESOLUTION_SOURCES)[number];

/**
 * Источники, ответу которых можно доверять при маршрутизации.
 *
 * Доменное правило: **вызов с неподтверждённым оператором не совершается вовсе**.
 * У всех партнёров тариф «безлимит внутри своей сети», поэтому ошибка стоит реальных
 * денег партнёра, а промежуточного варианта не существует (ADR-0013).
 */
const CONFIRMED_SOURCES: readonly ResolutionSource[] = ['lookup', 'manual'];

export function isConfirmedSource(source: ResolutionSource): boolean {
  return CONFIRMED_SOURCES.includes(source);
}
