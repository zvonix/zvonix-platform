/**
 * Общие определения колонок.
 *
 * Собраны в одном месте, чтобы «идентификатор», «отметка времени» и «значение из списка»
 * выглядели одинаково во всех таблицах. Расхождения в типах одноимённых колонок —
 * источник трудноуловимых ошибок сравнения и приведения на стыке модулей.
 */

import { sql, type SQL } from 'drizzle-orm';
import { bigint, type AnyPgColumn, timestamp, uuid } from 'drizzle-orm/pg-core';
import type { Id, MoneyAmount } from '@zvonix/shared';

/**
 * Первичный ключ: UUIDv7, который генерирует приложение.
 *
 * Значения по умолчанию на стороне базы намеренно нет. Идентификатор нужен до вставки —
 * на нём строится идемпотентность повторной обработки, — а колонка с `DEFAULT` молча
 * прощает забытое присваивание и выдаёт другой идентификатор, чем тот, что уже ушёл
 * в очередь или в лог.
 */
export function primaryId<T extends string>() {
  return uuid().$type<Id<T>>().primaryKey();
}

/** Ссылка на другую сущность с типом её идентификатора. */
export function idRef<T extends string>() {
  return uuid().$type<Id<T>>();
}

/**
 * Отметка времени.
 *
 * Всегда `timestamptz`. `timestamp` без зоны хранит момент, о котором неизвестно,
 * в каком поясе он записан; при разборе звонка, произошедшего в другом регионе,
 * это уже не восстановить.
 */
export function timestamptz() {
  return timestamp({ withTimezone: true, mode: 'date' });
}

/** Момент создания. Проставляет база: приложение не должно иметь возможности его подделать. */
export function createdAt() {
  return timestamptz().notNull().defaultNow();
}

/**
 * Момент последнего изменения.
 *
 * Обновляется на уровне ORM (`$onUpdate`), а не триггером. Триггер надёжнее, но невидим
 * тому, кто читает схему, а прямых `UPDATE` в обход репозиториев в проекте нет.
 * Если появятся — это станет причиной завести триггер, и решение нужно будет пересмотреть.
 */
export function updatedAt() {
  return timestamptz()
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());
}

/**
 * Денежная величина: целое число микроединиц валюты (1 рубль = 1 000 000).
 *
 * `bigint` в режиме `bigint`, а не `number`: копейки в числах с плавающей точкой
 * теряются молча, и обнаруживается это на сверке через месяц. Тип колонки —
 * `MoneyAmount` из `@zvonix/shared`, поэтому подставить сюда обычное число не даст компилятор.
 *
 * Округление выполняется один раз — при фиксации CDR, по правилу из тарифа.
 * Ни в одном промежуточном вычислении округления быть не должно.
 */
export function money() {
  return bigint({ mode: 'bigint' }).$type<MoneyAmount>();
}

/** Допустимый вид значения в ограничении: подставляется в текст SQL, поэтому проверяется. */
const SAFE_VALUE = /^[a-z][a-z0-9_]*$/;

/**
 * Ограничение «значение из списка» для текстовой колонки.
 *
 * Почему текст с `CHECK`, а не тип `enum` базы: см. ADR-0016. Коротко — изменение набора
 * значений у типа `enum` требует пересоздания типа и переписывания колонки, а ADR-0005
 * требует, чтобы разрушающие изменения выполнялись в два совместимых шага. У `CHECK`
 * такой шаг — обычный `DROP CONSTRAINT` / `ADD CONSTRAINT`.
 *
 * Значения приходят из констант `@zvonix/shared`, а не извне, но подставляются в текст SQL,
 * поэтому формат проверяется здесь: ошибка в списке должна падать при запуске,
 * а не превращаться в испорченную миграцию.
 */
export function oneOf(column: AnyPgColumn, values: readonly string[]): SQL {
  if (values.length === 0) {
    throw new Error('Список допустимых значений пуст');
  }
  for (const value of values) {
    if (!SAFE_VALUE.test(value)) {
      throw new Error(`Недопустимое значение перечисления: ${value}`);
    }
  }
  const list = sql.raw(values.map((value) => `'${value}'`).join(', '));
  return sql`${column} in (${list})`;
}
