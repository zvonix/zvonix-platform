/**
 * Поиск по части текста без учёта регистра.
 *
 * Отдельным местом, а не `ilike` по месту вызова, по одной причине — и она про русский
 * язык. PostgreSQL приводит регистр по локали базы, и в локали `C` **кириллица
 * не приводится вовсе**: `lower('ТАКСИ')` возвращает `ТАКСИ`, а `'Такси' ilike '%такси%'`
 * даёт «нет». Проверено на PostgreSQL 16 с `datcollate = C` (2026-09-07).
 *
 * Отказ при этом молчаливый: поиск не падает, он просто ничего не находит. Самый
 * неприятный вид ошибки — администратор ищет «такси» и делает вывод, что клиента нет.
 *
 * Локаль базы задаётся при её создании и потом не меняется, а на какой локали окажется
 * production, код знать не может. Поэтому сравнение идёт с **явно указанной** локалью
 * ICU: она есть в любой сборке PostgreSQL с ICU и не зависит от того, как создавали базу.
 */

import { sql, type SQL } from 'drizzle-orm';
import type { PgColumn } from 'drizzle-orm/pg-core';

/**
 * Локаль сравнения.
 *
 * `und` — «язык не указан»: правила Unicode по умолчанию. Русскому этого достаточно,
 * а привязка к `ru` добавила бы правила сортировки, которые в поиске по подстроке
 * ничего не меняют.
 */
const COLLATION = sql`"und-x-icu"`;

/**
 * Экранирует знаки шаблона `LIKE`.
 *
 * Без этого `%`, введённый в поле поиска, означает «что угодно», а `_` — «любой
 * символ»: отбор молча перестаёт отбирать. Обратная косая экранируется первой,
 * иначе она удвоит уже поставленные.
 */
function escapePattern(value: string): string {
  return value.replace(/[\\%_]/g, (match) => `\\${match}`);
}

/**
 * Условие «в колонке есть эта подстрока, регистр не важен».
 *
 * Пустая строка ищет всё — вызывающий обязан проверить это сам: «искать пустоту»
 * и «не искать» — разные намерения, и решать за него здесь неправильно.
 */
export function containsIgnoringCase(column: PgColumn, value: string): SQL {
  return sql`${column} collate ${COLLATION} ilike ${`%${escapePattern(value)}%`}`;
}

/**
 * Порядок по человекочитаемому названию.
 *
 * Та же болезнь, что и у поиска, только тише. В локали `C` сравнение идёт по кодам
 * символов, и заглавные буквы оказываются раньше строчных: «Яндекс» встаёт перед
 * «абв», а «ООО Ромашка» — перед «ООО ромашка». Латиница страдает так же, просто
 * там это привычнее глазу.
 *
 * Явная локаль ICU даёт порядок, которого человек и ждёт: регистр при сравнении
 * не главный, «ё» стоит после «е», цифры перед буквами.
 */
export function orderByText(column: PgColumn): SQL {
  return sql`${column} collate ${COLLATION} asc`;
}
