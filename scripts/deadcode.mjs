/**
 * Запуск knip с отключённой «сырой передачей» разбора.
 *
 * Обёртка нужна ровно ради одной переменной окружения, и она здесь, а не в строке
 * npm-скрипта, потому что `ПЕРЕМЕННАЯ=значение команда` — синтаксис POSIX-оболочки,
 * которого нет в cmd.exe. Скрипт должен запускаться и на Windows, и на Ubuntu.
 *
 * Почему выключаем: knip разбирает файлы через oxc, а тот в режиме «сырой передачи»
 * запрашивает непрерывный буфер размером больше четырёх гигабайт. На машине, где уже
 * работают база и пара процессов Node, такое выделение не проходит, и шаг проверки
 * падает с `RangeError: Array buffer allocation failed` — то есть по причине,
 * не имеющей отношения к качеству кода. Шаг проверки, который валится от занятости
 * памяти, вредит: его начинают игнорировать вместе с настоящими находками.
 *
 * Цена — доли секунды на этом шаге. Проверялось: разница в пределах погрешности.
 */

import { spawn } from 'node:child_process';
import process from 'node:process';

const child = spawn('knip', process.argv.slice(2), {
  stdio: 'inherit',
  // Без shell на Windows не находится knip.cmd из node_modules/.bin.
  shell: true,
  env: { ...process.env, KNIP_DISABLE_RAW_TRANSFER: '1' },
});

child.on('exit', (code, signal) => {
  process.exitCode = signal === null ? (code ?? 1) : 1;
});
