#!/usr/bin/env bash
# Единая точка проверки проекта.
# Один и тот же набор шагов запускается локально и в CI — иначе «у меня проходит»
# перестаёт что-либо значить.
#
# Интеграционным тестам нужна живая PostgreSQL (ADR-0006). Адрес — TEST_DATABASE_URL,
# по умолчанию локальная база zvonix_test. Если базы нет, шаг падает, а не пропускается:
# проверка, о пропуске которой никто не узнал, хуже отсутствующей.

set -euo pipefail
cd "$(dirname "$0")/.."

FAILED=()

step() {
  local name="$1"; shift
  echo ""
  echo "=== $name ==="
  if "$@"; then
    echo "--- $name: ok"
  else
    echo "--- $name: ПРОВАЛ"
    FAILED+=("$name")
  fi
}

# --- Шаги проверки -----------------------------------------------------------
# Порядок важен: сначала дешёвые и быстрые, потом дорогие.

step "Формат"    pnpm format:check
step "Линтер"    pnpm lint
step "Типы"      pnpm typecheck
step "Тесты"     pnpm test
step "Тесты с БД" pnpm test:integration

# --- Итог --------------------------------------------------------------------
echo ""
if [ ${#FAILED[@]} -eq 0 ]; then
  echo "Все проверки пройдены."
  exit 0
fi
echo "Провалено шагов: ${#FAILED[@]}"
printf '  - %s\n' "${FAILED[@]}"
exit 1
